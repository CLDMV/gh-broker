/**
 * gh-broker installer — one command for first install AND upgrade.
 *
 *   sudo node deploy/install.mjs [agent-user] [flags]
 *
 * Prerequisite: node >= 20. Idempotent: re-run to upgrade (config regenerated by
 * merge, existing secrets kept). Interactive by default; pass flags plus
 * --non-interactive for a single unattended command. See --help and
 * docs/deploy-architecture.md.
 */
import { readFileSync, readdirSync, existsSync, statSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import {
	run, has, isRoot, userExists, requireGid,
	ensureServiceUser, createAgentUser, addUserToGroup,
	pointNodeSymlinks, currentNodeBin, ensureDirs, installUnit,
	enableService, restartService, serviceActive, deployDist, writeConfigFile,
	trySystemdCredDecrypt, systemdCredsEncrypt, ensureCredsDir, writeCredsDropin, removeCredsDropin
} from "./lib/system.mjs";
import { promptLine, promptHidden, confirm, choose } from "./lib/prompt.mjs";
import { mergeConfig } from "./lib/config-merge.mjs";
import { writeSecretsFile, readSecretsFile, removeSecretsFile, referencedCredNames, detectSecretsProvider } from "./lib/secret-store.mjs";
import { smokeTest } from "./lib/smoke.mjs";
import { createNpmToken } from "./lib/npm-setup.mjs";
import { hostname } from "node:os";

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));
const SVC_USER = "gh-broker";
const SVC_GROUP = "gh-broker";
const CLIENTS_GROUP = "gh-broker-clients";
const APP_DIR = "/opt/gh-broker";
const DIST = join(REPO, "dist");
const DIST_ENTRY = join(DIST, "index.mjs");

const log = (m) => console.log(m);
const step = (m) => console.log(`\n==> ${m}`);
const die = (m) => {
	console.error(`gh-broker install: ${m}`);
	process.exit(1);
};

function readJson(path) {
	try {
		return JSON.parse(readFileSync(path, "utf8"));
	} catch {
		return null;
	}
}

const HELP = `gh-broker installer — install and upgrade in one command.

Usage: sudo node deploy/install.mjs [agent-user] [flags]

Flags:
  --agent-user <name>     the unprivileged user the agent runs as
                          (also positional; defaults to $SUDO_USER)
  --secrets-provider <p>  systemd-creds | file   (skips the prompt)
  --secrets-file <path>   JSON { "<cred-name>": "<token>" } to import tokens from
  --create-agent-user     create the agent user if missing (no confirm)
  --npm                   set up the npm integration (npm_scaffold), or rotate its
                          token: walks through an npm web login and creates the token
  --npm-scope <@scope>    scope npm_scaffold may create packages in (repeatable;
                          default: the existing setting, else @<first owner>)
  --npm-token-days <n>    lifetime of a newly created npm token (default 90)
  -y, --non-interactive   never prompt; fail if a value/decision is missing
  -h, --help              this help

Non-interactive credentials: for each not already stored, the token is taken from
--secrets-file, then env GH_BROKER_SECRET_<NAME> (NAME upper-cased, non-alnum -> _).
Example (unattended):
  sudo GH_BROKER_SECRET_CLDMV_READ=… GH_BROKER_SECRET_CLDMV_WRITE=… \\
    /usr/local/bin/node deploy/install.mjs --agent-user repo \\
    --secrets-provider systemd-creds --non-interactive`;

function parseArgs(argv) {
	const o = { positional: [], nonInteractive: false, createAgentUser: false, npm: false, npmScopes: [] };
	// Consume the value after a value-taking flag, failing if it's missing or is
	// itself a flag — so `--agent-user --secrets-provider file` can't silently take
	// "--secrets-provider" as the username and proceed with an unintended user.
	const value = (i, flag) => {
		const v = argv[i];
		if (v === undefined || v.startsWith("-")) die(`${flag} requires a value (see --help)`);
		return v;
	};
	for (let i = 0; i < argv.length; i++) {
		const a = argv[i];
		if (a === "-h" || a === "--help") o.help = true;
		else if (a === "-y" || a === "--non-interactive") o.nonInteractive = true;
		else if (a === "--create-agent-user") o.createAgentUser = true;
		else if (a === "--agent-user") o.agentUser = value(++i, a);
		else if (a === "--secrets-provider") o.provider = value(++i, a);
		else if (a === "--secrets-file") o.secretsFile = value(++i, a);
		else if (a === "--npm") o.npm = true;
		else if (a === "--npm-scope") o.npmScopes.push(value(++i, a));
		else if (a === "--npm-token-days") o.npmTokenDays = value(++i, a);
		else if (a.startsWith("-")) die(`unknown flag: ${a} (see --help)`);
		else o.positional.push(a);
	}
	return o;
}

const NPM_SCOPE = /^@[a-z0-9][a-z0-9._~-]*$/;
const NPM_TOKEN_REF = "cred:npm-token";

const envSecretKey = (name) => "GH_BROKER_SECRET_" + name.toUpperCase().replace(/[^A-Z0-9]/g, "_");

async function main() {
	const opts = parseArgs(process.argv.slice(2));
	if (opts.help) {
		log(HELP);
		return;
	}
	if (opts.provider && opts.provider !== "systemd-creds" && opts.provider !== "file") {
		die(`--secrets-provider must be "systemd-creds" or "file"`);
	}
	for (const s of opts.npmScopes) if (!NPM_SCOPE.test(s)) die(`--npm-scope must be a lowercase npm scope like "@cldmv", got "${s}"`);
	if (opts.npmTokenDays !== undefined && !/^[1-9][0-9]{0,2}$/.test(opts.npmTokenDays)) die("--npm-token-days must be a whole number of days");
	const importTokens = opts.secretsFile ? readJson(opts.secretsFile) : {};
	// Must be a plain JSON object of { "<name>": "<token>" } — an array parses as an
	// "object" but yields no tokens, so reject it explicitly rather than importing nothing.
	if (opts.secretsFile && (!importTokens || typeof importTokens !== "object" || Array.isArray(importTokens))) {
		die(`--secrets-file: ${opts.secretsFile} must be a JSON object of { "<name>": "<token>" }`);
	}

	if (!isRoot()) die("must run as root: sudo node deploy/install.mjs [agent-user] [flags]");
	if (process.platform !== "linux") {
		die(`only Linux is implemented today (platform: ${process.platform}). The path/secret/service seams are ready; the impls are not.`);
	}

	step("prerequisites");
	for (const cmd of ["systemctl", "useradd", "getent", "sudo"]) if (!has(cmd)) die(`missing required command: ${cmd}`);
	for (const cmd of ["socat", "rsync"]) if (!has(cmd)) log(`  note: '${cmd}' not found — ${cmd === "socat" ? "the agent socket bridge needs it" : "will fall back to a plain copy"}`);

	// --- agent user ---
	step("agent user");
	let agentUser = opts.agentUser || opts.positional[0] || process.env.SUDO_USER || "";
	if (!agentUser) {
		if (opts.nonInteractive) die("no agent user — pass --agent-user <name>");
		agentUser = await promptLine("Which unprivileged user does the agent run as? ");
	}
	if (!agentUser) die("no agent user given");
	if (!userExists(agentUser)) {
		const create = opts.createAgentUser || (!opts.nonInteractive && (await confirm(`User "${agentUser}" does not exist. Create it (plain, no sudo)?`)));
		if (!create) die(`agent user "${agentUser}" missing — create it first or pass --create-agent-user`);
		createAgentUser(agentUser);
		log(`  created "${agentUser}"`);
	} else {
		log(`  "${agentUser}" exists`);
	}

	// --- build if needed ---
	// This installer requires root, but dist/ and node_modules/ are generated INSIDE
	// the repo checkout itself — not the deploy target (/opt/gh-broker, a directory
	// the installer owns outright and correctly chowns to the gh-broker service user
	// via deployDist() below). The checkout already has an owner: whoever owns this
	// very script file. Build AS that owner via `sudo -u '#<uid>'` — sudo resolves
	// that uid's home directory, primary group, AND full supplementary groups itself
	// (exactly like a real login), so generated files are correct from the moment
	// they're created — never chown, which is neither cross-platform nor necessary
	// once nothing is ever created with the wrong owner to begin with.
	const nodeModulesDir = join(REPO, "node_modules");
	const buildUid = statSync(fileURLToPath(import.meta.url)).uid;
	const asBuildOwner = (cmd, args) => run("sudo", ["-u", `#${buildUid}`, cmd, ...args], { cwd: REPO, stdio: "inherit" });

	// A prior root-run build (an older version of this script, or a manual `sudo npm
	// run build`) can leave dist/ or node_modules/ owned by root instead. Detect that
	// and rebuild rather than reuse it — root can always remove a root-owned
	// directory (regular DAC checks don't apply to it), where the build subprocess
	// (running as the checkout owner) could not. This makes re-running the installer
	// self-healing with no separate manual fix ever required.
	const distStale = existsSync(DIST_ENTRY) && statSync(DIST_ENTRY).uid !== buildUid;
	const modulesStale = existsSync(nodeModulesDir) && statSync(nodeModulesDir).uid !== buildUid;
	if (!existsSync(DIST_ENTRY) || distStale || modulesStale) {
		step(distStale || modulesStale ? "build (owned by a different user — rebuilding)" : "build (dist not found)");
		if (!has("npm")) die(`dist/ is missing and 'npm' is not installed — build the bundle first (npm run build) or install npm, then re-run`);
		if (distStale) rmSync(DIST, { recursive: true, force: true });
		if (modulesStale) rmSync(nodeModulesDir, { recursive: true, force: true });
		if (!existsSync(nodeModulesDir)) asBuildOwner("npm", ["ci"]);
		asBuildOwner("npm", ["run", "build"]);
	}

	// --- resolve deployed paths from the daemon itself (one resolver, no drift) ---
	const paths = JSON.parse(run(currentNodeBin(), [DIST_ENTRY, "--print-paths"]).stdout);
	const configDir = dirname(paths.config);
	log(`  config:  ${paths.config}`);
	log(`  secrets: ${paths.secrets}`);

	// --- users, groups, dirs, node symlink ---
	step("service user, groups, directories");
	ensureServiceUser(SVC_USER, SVC_GROUP, CLIENTS_GROUP);
	addUserToGroup(agentUser, CLIENTS_GROUP);
	ensureDirs(configDir, APP_DIR, SVC_USER, SVC_GROUP);
	const linked = pointNodeSymlinks(currentNodeBin());
	log(`  node symlink -> ${currentNodeBin()} (${linked.join(", ")})`);

	// --- config: merge(example, current) ---
	step("config (merge example + current)");
	const example = readJson(join(REPO, "config.example.json"));
	if (!example) die("config.example.json missing or invalid");
	const current = readJson(paths.config); // null on first install
	const merged = mergeConfig(example, current);

	// --- npm integration (npm_scaffold): opt-in ---
	// Offered on a first interactive install; afterwards `--npm` enables it or, when it is
	// already enabled, rotates the token. Either way a new token is created by driving the
	// npm web login + token creation from here (see lib/npm-setup.mjs), unless the operator
	// supplied one through --secrets-file/env.
	step("npm integration");
	let npmMint = false;
	if (opts.npm || (!merged.npm && current === null && !opts.nonInteractive && (await confirm("Enable npm_scaffold (create new npm packages and their trusted publishers)?")))) {
		let scopes = opts.npmScopes.length ? opts.npmScopes : merged.npm?.scopes;
		if (!scopes?.length) {
			const fallback = `@${Object.keys(merged.owners ?? {})[0] ?? ""}`.toLowerCase();
			const answer = opts.nonInteractive ? fallback : (await promptLine(`  npm scope(s) to allow, comma-separated [${fallback}]: `)) || fallback;
			scopes = answer.split(",").map((s) => s.trim()).filter(Boolean);
		}
		for (const s of scopes) if (!NPM_SCOPE.test(s)) die(`npm scope must be a lowercase npm scope like "@cldmv", got "${s}"`);
		merged.npm = { ...(merged.npm ?? {}), token: merged.npm?.token ?? NPM_TOKEN_REF, scopes };
		npmMint = true;
		log(`  ${current?.npm ? "rotating the npm token" : "enabling"} for ${scopes.join(", ")}`);
	} else {
		log(merged.npm ? `  enabled for ${merged.npm.scopes.join(", ")} (rotate the token with --npm)` : "  not enabled (enable with --npm)");
	}
	const npmTokenName = merged.npm?.token?.startsWith("cred:") ? merged.npm.token.slice("cred:".length) : undefined;

	// --- secrets: operator chooses the backend, then tokens are stored in it ---
	step("secrets");
	const needed = referencedCredNames(merged);
	const existingFile = readSecretsFile(paths.secrets); // {} if none
	const credsDir = join(configDir, "creds"); // systemd-creds location
	const priorProvider = merged.secrets?.provider ?? "systemd-creds";
	let provider = opts.provider;
	if (!provider) {
		// An existing install already has a backend — keep it rather than asking again. Only a
		// first install (or an ambiguous one) falls through to the prompt.
		let credNames = [];
		try {
			credNames = readdirSync(credsDir).filter((f) => f.endsWith(".cred")).map((f) => f.slice(0, -".cred".length));
		} catch {
			// no creds dir yet — nothing encrypted on disk
		}
		const detected = detectSecretsProvider({ configured: current?.secrets?.provider, credNames, fileTokenNames: Object.keys(existingFile) });
		if (detected) {
			provider = detected;
			log(`  keeping existing backend: ${provider} (change it with --secrets-provider)`);
		}
	}
	if (!provider) {
		provider = opts.nonInteractive
			? priorProvider
			: await choose(
					"How should the PAT credentials be stored at rest?",
					[
						{ key: "systemd-creds", label: "systemd-creds — encrypted, host-bound (recommended; Linux/systemd)" },
						{ key: "file", label: "file — plaintext JSON 0640 root:gh-broker (portable, platform-neutral)" }
					],
					priorProvider === "file" ? 2 : 1
				);
	}
	log(`  backend: ${provider}`);
	merged.secrets = { provider, ...(merged.secrets?.path ? { path: merged.secrets.path } : {}) };

	// The App private key (if config.app is ever set) is a multi-line PEM the
	// single-line prompt can't accept — it must be supplied out-of-band.
	const appKeyName = merged.app?.privateKey?.startsWith("cred:") ? merged.app.privateKey.slice("cred:".length) : undefined;

	// A token the operator EXPLICITLY supplied for this run — --secrets-file, then
	// env GH_BROKER_SECRET_<NAME>. Its presence is what makes a re-run ROTATE an
	// existing credential rather than keep it. Only non-empty strings count.
	const explicitToken = (name) => {
		const fromImport = importTokens && importTokens[name];
		if (typeof fromImport === "string" && fromImport) return fromImport;
		const fromEnv = process.env[envSecretKey(name)];
		if (typeof fromEnv === "string" && fromEnv) return fromEnv;
		return undefined;
	};

	// Resolve a token's plaintext, only when needed. Precedence:
	//   plaintext secrets file (file → creds migration) → explicit --secrets-file/env
	//   (a new value = rotation) → decrypt an existing legacy .cred (migration/keep) →
	//   prompt (interactive only). Explicit MUST beat decrypt, or a rotation would
	//   just re-encrypt the old decrypted value. Every source yields a non-empty STRING.
	const mintsNpmToken = (name) => name === npmTokenName && npmMint && explicitToken(name) === undefined;
	const resolveToken = async (name) => {
		if (mintsNpmToken(name)) {
			if (opts.nonInteractive) die(`creating the npm token needs a browser login and prompts — run interactively, or supply an existing token via --secrets-file or env ${envSecretKey(name)}`);
			try {
				const out = await createNpmToken({
					...(merged.npm.registry ? { registry: merged.npm.registry } : {}),
					scopes: merged.npm.scopes,
					tokenName: `gh-broker ${hostname()} ${new Date().toISOString().slice(0, 10)}`,
					...(opts.npmTokenDays ? { days: Number(opts.npmTokenDays) } : {}),
					promptHidden,
					promptLine,
					log
				});
				log(`  ${name}: created${out.expires ? ` (expires ${out.expires.slice(0, 10)})` : ""}`);
				return out.token;
			} catch (err) {
				die(`npm token setup failed: ${err.message}`);
			}
		}
		const fromFile = existingFile[name];
		if (typeof fromFile === "string" && fromFile) return fromFile;
		const explicit = explicitToken(name);
		if (explicit) return explicit;
		const dec = trySystemdCredDecrypt(name, join(credsDir, `${name}.cred`));
		if (dec) {
			log(`  ${name}: migrated from systemd-creds`);
			return dec;
		}
		if (opts.nonInteractive) die(`missing credential "${name}" — provide via --secrets-file or env ${envSecretKey(name)}`);
		if (name === appKeyName) {
			die(`credential "${name}" is a GitHub App private key (multi-line PEM); the single-line prompt can't accept it — supply it via --secrets-file or env ${envSecretKey(name)}`);
		}
		const entered = await promptHidden(`  ${name} (input hidden): `);
		if (!entered) die(`empty value for "${name}"`);
		return entered;
	};

	if (provider === "systemd-creds") {
		ensureCredsDir(configDir, SVC_GROUP);
		for (const name of needed) {
			const credFile = join(credsDir, `${name}.cred`);
			const existed = existsSync(credFile);
			// Re-encrypt (rotate) only when the operator supplies a new value — a
			// plaintext entry (file → creds migration) or an explicit --secrets-file/env
			// token. On a plain re-run with no new value, keep the existing cred as-is.
			const rotate = Boolean(existingFile[name]) || explicitToken(name) !== undefined || mintsNpmToken(name);
			if (existed && !rotate) {
				log(`  ${name}: existing systemd-creds kept`);
				continue;
			}
			systemdCredsEncrypt(name, await resolveToken(name), credFile);
			log(`  ${name}: ${existed ? "rotated" : "encrypted"} (systemd-creds)`);
		}
		writeCredsDropin(needed, credsDir);
		// Now that creds are encrypted, a plaintext secrets file from a previous
		// `file` install must not linger — it would defeat "encrypted at rest".
		if (existsSync(paths.secrets)) {
			removeSecretsFile(paths.secrets);
			log(`  removed plaintext secrets file (now using systemd-creds)`);
		}
	} else {
		const tokens = { ...existingFile };
		for (const name of needed) {
			if (!tokens[name] || mintsNpmToken(name)) tokens[name] = await resolveToken(name);
		}
		writeSecretsFile(paths.secrets, tokens, { gid: requireGid(SVC_GROUP) });
		removeCredsDropin(); // no systemd-creds delivery under the file provider
	}
	writeConfigFile(paths.config, merged, SVC_GROUP);

	// --- validate with the real loader before deploying ---
	step("validate config");
	run(currentNodeBin(), [DIST_ENTRY, "--check", "--config", paths.config], {
		env: { ...process.env, GH_BROKER_SECRETS: paths.secrets },
		stdio: "inherit"
	});

	// --- deploy unit + dist, restart ---
	step("deploy");
	installUnit(join(REPO, "deploy", "gh-broker.service"));
	enableService();
	deployDist(DIST, APP_DIR, SVC_USER, SVC_GROUP);
	restartService();
	log(`  service: ${serviceActive()}`);

	// --- smoke test ---
	step("smoke test");
	const sock = merged.listen.replace(/^unix:/, "");
	try {
		const r = await smokeTest(sock);
		log(`  ✅ broker answered — ${r.tools.length} tools advertised${r.roundTrip ? `; ${r.roundTrip}` : ""}`);
	} catch (e) {
		die(`smoke test failed: ${e.message}\n  check: journalctl -u gh-broker -n 30 --no-pager`);
	}

	log(`\n✅ gh-broker installed. Point the agent's MCP client at the socket:`);
	log(`   "github": { "type": "stdio", "command": "socat", "args": ["STDIO", "UNIX-CONNECT:${sock}"] }`);
	log(`   (re-login as "${agentUser}" so its ${CLIENTS_GROUP} membership is active)`);
}

main().catch((e) => die(e.message));
